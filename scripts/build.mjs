// Builds dist/ from the source files:
//   dist/mi-contabilidad-ds.css      tokens + base + every component (in this order)
//   dist/mi-contabilidad-ds.js       charts + icons as a classic script → window.MCChart, window.MCIcon
//   dist/mi-contabilidad-ds-icons.svg the icon sprite (<symbol id="ico-…">)
//   dist/icons/<name>.svg            one file per icon (design tools, other platforms)
//   dist/tokens.json                 every token in the W3C Design Tokens format (AI, Figma, other platforms)
//   dist/AGENTS.md                   instructions for AI assistants (copy of AGENTS.md)
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';

const CSS = [
  'tokens/tokens.css', 'tokens/base.css', 'icons/icons.css',
  'components/button/button.css', 'components/tab/tab.css', 'components/selectors/selectors.css',
  'components/card/card.css', 'components/list/list.css', 'components/table/table.css',
  'components/input/input.css', 'components/result/result.css', 'components/feedback/feedback.css',
  'components/dialog/dialog.css', 'components/chart/chart.css', 'components/menu/menu.css',
];
const { version } = JSON.parse(readFileSync('package.json', 'utf8'));
const banner = `/* Mi Contabilidad Design System v${version} — generated by scripts/build.mjs, do not edit by hand */\n`;

mkdirSync('dist', { recursive: true });
writeFileSync('dist/mi-contabilidad-ds.css', banner + CSS.map((f) => `/* ── ${f} ── */\n${readFileSync(f, 'utf8').trim()}\n`).join('\n'));

// One classic script for the single-file app: charts + icons → window.MCChart, window.MCIcon
const strip = (f) => readFileSync(f, 'utf8').replace(/^export (function|const) /gm, '$1 ');
writeFileSync('dist/mi-contabilidad-ds.js', `${banner}(function () {
${strip('icons/icons.js')}
${strip('components/chart/chart.js')}
window.MCIcon = { icon, ICONS, iconSprite };
window.MCChart = { lineChart, barChart, formatEuro };
})();
`);

// SVG sprite: <use href="#ico-trash"/>
const { iconSprite, ICONS } = await import('../icons/icons.js');
writeFileSync('dist/mi-contabilidad-ds-icons.svg', iconSprite().replace(' style="display:none"', ''));

// One SVG per icon: 16 × 16, single path, currentColor (black when opened on its own)
rmSync('dist/icons', { recursive: true, force: true });
mkdirSync('dist/icons', { recursive: true });
for (const [name, d] of Object.entries(ICONS)) {
  writeFileSync(`dist/icons/${name}.svg`,
    `<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16" fill="currentColor"><title>${d.label}</title><path d="${d.path}"/></svg>\n`);
}
// Tokens as JSON (W3C Design Tokens format)
const { tokensToJson } = await import('./tokens-json.mjs');
const tj = tokensToJson(readFileSync('tokens/tokens.css', 'utf8'));
writeFileSync('dist/tokens.json', JSON.stringify(tj.json, null, 2) + '\n');
writeFileSync('dist/AGENTS.md', readFileSync('AGENTS.md', 'utf8'));

// Sub-system · Asistente inteligente: its own CSS (load it after mi-contabilidad-ds.css) and its own tokens
const AI_CSS = ['assistant/tokens.css', 'assistant/assistant.css'];
writeFileSync('dist/mi-contabilidad-ds-assistant.css', banner.replace('Design System', 'Design System · Asistente inteligente') + AI_CSS.map((f) => `/* ── ${f} ── */\n${readFileSync(f, 'utf8').trim()}\n`).join('\n'));
const ai = tokensToJson(readFileSync('assistant/tokens.css', 'utf8'), readFileSync('tokens/tokens.css', 'utf8'));
ai.json.$description = 'Asistente inteligente (sub-system) tokens. They build on dist/tokens.json: references like {color.action.primary} point there. Generated from assistant/tokens.css: do not edit by hand.';
writeFileSync('dist/tokens-assistant.json', JSON.stringify(ai.json, null, 2) + '\n');

// Sub-system · Acceso fácil: its own CSS (load it after mi-contabilidad-ds.css) and its own tokens
const AF_CSS = ['acceso/tokens.css', 'acceso/acceso.css'];
writeFileSync('dist/mi-contabilidad-ds-acceso.css', banner.replace('Design System', 'Design System · Acceso fácil') + AF_CSS.map((f) => `/* ── ${f} ── */\n${readFileSync(f, 'utf8').trim()}\n`).join('\n'));
const af = tokensToJson(readFileSync('acceso/tokens.css', 'utf8'), readFileSync('tokens/tokens.css', 'utf8'));
af.json.$description = 'Acceso fácil (sub-system) tokens. They build on dist/tokens.json: references like {color.action.primary} point there. Generated from acceso/tokens.css: do not edit by hand.';
writeFileSync('dist/tokens-acceso.json', JSON.stringify(af.json, null, 2) + '\n');
console.log(`dist/ built (v${version}): ${CSS.length} CSS files + script (charts, icons) + icon sprite + ${Object.keys(ICONS).length} icon files + tokens.json (${tj.count} tokens) · assistant: CSS + tokens-assistant.json (${ai.count} tokens) · acceso: CSS + tokens-acceso.json (${af.count} tokens)`);
